#!/usr/bin/env python3
"""Portable workspace and literal application rules, validated before reload."""
import argparse
import copy
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

from backend import lock
from preferences import revision, roots, transaction

DEFAULTS = {'version': 1, 'general': {}, 'workspaces': [], 'rules': []}
LAYOUTS = ('dwindle', 'master', 'scrolling')
GENERAL = {'layout': LAYOUTS, 'resizeOnBorder': (False, True), 'followMouse': (0, 1, 2, 3)}


def text(value, maximum=200):
    return isinstance(value, str) and len(value) <= maximum and not any(ord(c) < 32 for c in value)


def integer(value, low, high):
    return type(value) is int and low <= value <= high


def validate(data):
    if not isinstance(data, dict) or set(data) != set(DEFAULTS) or type(data['version']) is not int or data['version'] != 1:
        raise ValueError('Unsupported workspace/rule preferences')
    if not isinstance(data['general'], dict) or set(data['general']) - set(GENERAL):
        raise ValueError('Unknown window behavior preference')
    for key, value in data['general'].items():
        if value not in GENERAL[key] or (key == 'resizeOnBorder' and type(value) is not bool) or (key == 'followMouse' and type(value) is not int):
            raise ValueError('Invalid window behavior preference')
    if not isinstance(data['workspaces'], list) or len(data['workspaces']) > 99:
        raise ValueError('Choose at most 99 workspaces')
    seen = set()
    for row in data['workspaces']:
        if not isinstance(row, dict) or (set(row) - {'floating', 'pseudotiled'}) != {'id', 'name', 'layout', 'persistent'} or not integer(row['id'], 1, 99) or row['id'] in seen:
            raise ValueError('Workspace numbers must be unique, from 1 to 99')
        if not text(row['name'], 60) or row['layout'] not in ('inherit', *LAYOUTS) or type(row['persistent']) is not bool:
            raise ValueError('Invalid workspace name, layout, or persistence')
        if 'floating' in row and type(row['floating']) is not bool:
            raise ValueError('Workspace floating preference must be enabled or disabled')
        if 'pseudotiled' in row and type(row['pseudotiled']) is not bool:
            raise ValueError('Workspace pseudotiling preference must be enabled or disabled')
        if row.get('floating') and row.get('pseudotiled'):
            raise ValueError('Choose floating windows or pseudotiling for each workspace')
        seen.add(row['id'])
    if not isinstance(data['rules'], list) or len(data['rules']) > 100:
        raise ValueError('Choose at most 100 application rules')
    seen = set()
    for row in data['rules']:
        if not isinstance(row, dict) or set(row) != {'class', 'mode', 'workspace', 'pin', 'noAnimations', 'width', 'height'}:
            raise ValueError('Invalid application rule')
        if not text(row['class']) or not row['class'].strip() or row['class'] in seen:
            raise ValueError('Each rule needs a unique application class')
        if row['mode'] not in ('inherit', 'float', 'tile') or not integer(row['workspace'], 0, 99) or type(row['pin']) is not bool or type(row['noAnimations']) is not bool:
            raise ValueError('Invalid application rule behavior')
        if not all(integer(row[key], 0, 4096) and (row[key] == 0 or row[key] >= 200) for key in ('width', 'height')) or bool(row['width']) != bool(row['height']):
            raise ValueError('Enter both window dimensions from 200 to 4096 pixels, or leave both at 0')
        if (row['pin'] or row['width']) and row['mode'] != 'float':
            raise ValueError('Pinning and window size require a floating rule')
        seen.add(row['class'])
    return data


def paths():
    config, _ = roots()
    return config / 'hyprshell/behavior.json', config / 'hyprshell/behavior.lua', config / 'hypr/hyprland.lua'


def saved():
    path = paths()[0]
    return validate(json.loads(path.read_text())) if path.exists() else copy.deepcopy(DEFAULTS)


def encode(value):
    if isinstance(value, dict):
        return '{' + ', '.join(key + ' = ' + encode(value) for key, value in value.items()) + '}'
    if isinstance(value, list):
        return '{' + ', '.join(encode(item) for item in value) + '}'
    return json.dumps(value, ensure_ascii=False)


def render(data):
    validate(data)
    config = {}
    for key, value in data['general'].items():
        category, name = {'layout': ('general', 'layout'), 'resizeOnBorder': ('general', 'resize_on_border'), 'followMouse': ('input', 'follow_mouse')}[key]
        config.setdefault(category, {})[name] = value
    lines = ['-- Generated by Hyprshell workspace and application rules.']
    if config:
        lines.append('hl.config(' + encode(config) + ')')
    for row in data['workspaces']:
        rule = {'workspace': str(row['id']), 'persistent': row['persistent']}
        if row['name']: rule['default_name'] = row['name']
        if row['layout'] != 'inherit': rule['layout'] = row['layout']
        lines.append('hl.workspace_rule(' + encode(rule) + ')')
    for index, row in enumerate(data['rules']):
        rule = {'name': 'hyprshell-user-' + str(index), 'match': {'class': '^' + re.escape(row['class']) + '$'}}
        if row['mode'] != 'inherit': rule[row['mode']] = True
        if row['workspace']: rule['workspace'] = str(row['workspace']) + ' silent'
        if row['pin']: rule['pin'] = True
        if row['noAnimations']: rule['no_anim'] = True
        if row['width']: rule['size'] = [row['width'], row['height']]
        lines.append('hl.window_rule(' + encode(rule) + ')')
    floating = [row['id'] for row in data['workspaces'] if row.get('floating', False)]
    if floating:
        # Run after application placement rules, including explicit tile rules.
        for ident in floating:
            lines.append('hl.window_rule(' + encode({'name': 'hyprshell-workspace-float-' + str(ident),
                'match': {'workspace': str(ident)}, 'float': True}) + ')')
        lines.extend([
            'local floatingWorkspaces = {' + ', '.join('[' + str(ident) + '] = true' for ident in floating) + '}',
            'local function floatWorkspaceWindow(w)',
            '    if w and w.mapped and w.workspace and floatingWorkspaces[w.workspace.id] and not w.floating and w.fullscreen == 0 then',
            '        hl.dispatch(hl.dsp.window.float({ window = w, action = "set" }))',
            '    end',
            'end',
            'hl.on("window.open", floatWorkspaceWindow)',
            'hl.on("window.move_to_workspace", floatWorkspaceWindow)',
            'hl.on("window.fullscreen", floatWorkspaceWindow)',
            'hl.on("config.reloaded", function()',
            '    for _, w in ipairs(hl.get_windows()) do floatWorkspaceWindow(w) end',
            'end)',
        ])
    pseudotiled = [row['id'] for row in data['workspaces'] if row.get('pseudotiled', False)]
    if pseudotiled:
        for ident in pseudotiled:
            lines.append('hl.window_rule(' + encode({'name': 'hyprshell-workspace-pseudo-' + str(ident),
                'match': {'workspace': str(ident)}, 'tile': True, 'pseudo': True}) + ')')
        lines.extend([
            'local pseudotiledWorkspaces = {' + ', '.join('[' + str(ident) + '] = true' for ident in pseudotiled) + '}',
            'local function pseudotileWorkspaceWindow(w)',
            '    if w and w.mapped and w.workspace and pseudotiledWorkspaces[w.workspace.id] and w.fullscreen == 0 then',
            '        if w.floating then hl.dispatch(hl.dsp.window.float({ window = w, action = "unset" })) end',
            '        hl.dispatch(hl.dsp.window.pseudo({ window = w, action = "enable" }))',
            '    end',
            'end',
            'hl.on("window.open", pseudotileWorkspaceWindow)',
            'hl.on("window.move_to_workspace", pseudotileWorkspaceWindow)',
            'hl.on("window.fullscreen", pseudotileWorkspaceWindow)',
            'hl.on("config.reloaded", function()',
            '    for _, w in ipairs(hl.get_windows()) do pseudotileWorkspaceWindow(w) end',
            'end)',
        ])
    return '\n'.join(lines) + '\n'


def parse_lua(source):
    with tempfile.TemporaryDirectory(prefix='hyprshell-rules-') as directory:
        path = Path(directory) / 'rules.lua'; path.write_text(source)
        result = subprocess.run(['Hyprland', '--verify-config', '--config', str(path)], capture_output=True, text=True, timeout=15)
        if result.returncode or 'config ok' not in result.stdout.lower():
            raise ValueError('The compositor rejected these workspace/rule settings. Review them before applying.')


def reload_live():
    if not os.environ.get('HYPRLAND_INSTANCE_SIGNATURE'):
        return
    result = subprocess.run(['hyprctl', 'reload'], capture_output=True, text=True, timeout=15)
    errors = subprocess.run(['hyprctl', 'configerrors'], capture_output=True, text=True, timeout=10)
    if result.returncode or errors.returncode or errors.stdout.strip().lower() not in ('', 'ok'):
        raise ValueError('The desktop could not apply these rules. Previous files were restored; check desktop access and retry.')


def save(data, expected):
    data = validate(data); source = render(data); parse_lua(source)
    _, state = roots()
    with lock(state / 'behavior.lock'):
        if expected != revision(paths()):
            raise ValueError('Workspace/rule settings changed elsewhere. Refresh before applying.')
        target, generated, main = paths()
        if not main.is_file():
            raise ValueError('A Hyprland Lua configuration is required for these controls.')
        original = main.read_text(); changes = {target: json.dumps(data, indent=2) + '\n', generated: source}
        if '-- Hyprshell behavior rules' not in original:
            changes[main] = original.rstrip() + '\n\n-- Hyprshell behavior rules\ndofile(' + json.dumps(str(generated), ensure_ascii=False) + ')\n'
        try:
            backup = transaction(changes, 'behavior', reload_live)
        except Exception:
            try: reload_live()
            except Exception: pass
            raise
    return {'ok': True, 'backup': backup, 'message': 'Workspace and application rules saved. Floating and pseudotiling workspace preferences also apply to existing windows and windows moved in. Application placement and size apply to newly opened windows.' + (' They load at the next session.' if not os.environ.get('HYPRLAND_INSTANCE_SIGNATURE') else '')}


def toggle_workspace(mode):
    if mode not in ('floating', 'pseudotiled'):
        raise ValueError('Unknown workspace placement mode.')
    active = subprocess.run(['hyprctl', '-j', 'activeworkspace'], capture_output=True, text=True, timeout=5)
    if active.returncode:
        raise ValueError('The active workspace could not be read. Check desktop access and retry.')
    workspace = json.loads(active.stdout).get('id')
    if not integer(workspace, 1, 99):
        raise ValueError('Workspace placement toggles require a numbered workspace from 1 to 99.')
    _, state = roots()
    # Serialize shortcut presses; save still checks revisions against Settings edits.
    with lock(state / 'behavior-shortcut.lock'):
        expected = revision(paths())
        data = saved()
        row = next((row for row in data['workspaces'] if row['id'] == workspace), None)
        if row is None:
            row = {'id': workspace, 'name': '', 'layout': 'inherit', 'persistent': False}
            data['workspaces'].append(row)
        enabled = not row.get(mode, False)
        row[mode] = enabled
        other = 'pseudotiled' if mode == 'floating' else 'floating'
        switched = enabled and row.get(other, False)
        if enabled:
            row[other] = False
        result = save(data, expected)
    labels = {'floating': 'Auto floating', 'pseudotiled': 'Auto pseudotiling'}
    message = f"Workspace {workspace}: {labels[mode]} {'enabled' if enabled else 'disabled'}"
    if switched:
        message += f'; {labels[other].lower()} disabled'
    if not enabled:
        message += ' (existing window placement kept)'
    return {**result, 'workspace': workspace, 'enabled': enabled, 'message': message}


def placement_toast(message, failed=False):
    # Use the shell's normal notification cards and delivery preferences.
    try:
        subprocess.run(['notify-send', '--app-name=Hyprshell', '--expire-time=3000',
                        '--icon=' + ('dialog-error' if failed else 'view-grid-symbolic'),
                        '--', 'Workspace placement', message],
                       capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.SubprocessError):
        pass


def status():
    classes, discovery = [], ''
    try:
        result = subprocess.run(['hyprctl', '-j', 'clients'], capture_output=True, text=True, timeout=5)
        if result.returncode: raise ValueError()
        clients = json.loads(result.stdout)
        classes = sorted({row['class'] for row in clients if text(row.get('class')) and row['class']})
    except (OSError, ValueError, TypeError, KeyError, AttributeError, subprocess.SubprocessError):
        discovery = 'Running application discovery is unavailable in this session. You can enter the application class manually.'
    return {'ok': True, 'settings': saved(), 'revision': revision(paths()), 'classes': classes, 'discoveryMessage': discovery}


def request(payload):
    if payload.get('operation') == 'status': return status()
    if payload.get('operation') == 'save':
        result = save(payload.get('settings'), payload.get('expected'))
        return {**status(), **result}
    raise ValueError('Unknown workspace/rule operation.')


def main():
    parser = argparse.ArgumentParser()
    operation = parser.add_mutually_exclusive_group(required=True)
    operation.add_argument('--request-json')
    operation.add_argument('--toggle-workspace', choices=('floating', 'pseudotiled'))
    args = parser.parse_args()
    try:
        result = toggle_workspace(args.toggle_workspace) if args.toggle_workspace else request(json.loads(args.request_json))
    except (ValueError, OSError, subprocess.SubprocessError) as error:
        result = {'ok': False, 'message': str(error) if isinstance(error, ValueError) else 'Workspace/rule settings could not be updated. Refresh and retry.'}
    if args.toggle_workspace:
        placement_toast(result['message'], failed=not result['ok'])
    print(json.dumps(result)); return 0 if result['ok'] else 1


if __name__ == '__main__': sys.exit(main())
